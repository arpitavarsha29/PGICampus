export function canSeeRecord(
  role: Role,
  record: {
    scope?: string;
    category?: string;
    location?: string;
    class?: string;
    dept?: string;
    inst?: string;
    studentClass?: string;
    studentDept?: string;
    studentInst?: string;
  }
): boolean {
  if (role.kind === 'central') return true;

  const targetInst = record.studentInst || record.inst;
  const targetDept = record.studentDept || record.dept;
  const targetClass = record.studentClass || record.class;

  if (role.kind === 'hostel') {
    return !!(
      record.scope?.includes('Hostel') ||
      record.category === 'Hostel' ||
      record.category === 'Washroom' ||
      record.location?.includes('Hostel')
    );
  }

  if (role.kind === 'exam') return true;

  if (role.kind === 'class') {
    return !!(
      (targetClass && targetClass.includes('CSE-A')) ||
      (record.scope && record.scope.includes('CSE'))
    );
  }

  if (role.kind === 'department') {
    return (
      targetDept === role.department ||
      !!(record.scope && record.scope.includes(role.department || ''))
    );
  }

  return (
    !targetInst ||
    targetInst === role.institution ||
    !!(record.scope && record.scope.startsWith(role.institution || ''))
  );
}
